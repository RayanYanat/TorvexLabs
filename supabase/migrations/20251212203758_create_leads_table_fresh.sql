/*
  # Create Leads Table (Fresh Start)

  1. New Tables
    - `leads`
      - `id` (bigint, primary key, auto-increment) - Unique identifier for each lead
      - `created_at` (timestamptz, default now()) - Timestamp when lead was created
      - `full_name` (text, not null) - Full name of the lead
      - `company_name` (text, nullable) - Company name of the lead
      - `email` (text, not null, unique) - Email address of the lead
      - `service` (text, nullable) - Service they're interested in
      - `budget` (integer, nullable) - Budget amount in dollars
      - `message` (text, nullable) - Additional message from the lead

  2. Security
    - Enable RLS on `leads` table
    - Add policy to allow anonymous users to insert leads (for chatbot form)
    - This is a public-facing form, so inserts must work without authentication

  3. Indexes
    - Unique index on email to prevent duplicate submissions
    - Index on created_at for efficient sorting

  4. Important Notes
    - Email is unique to prevent duplicate lead submissions
    - Anonymous insert policy allows chatbot form submissions
    - Budget is stored as integer (cents or dollars, depending on frontend logic)
    - All other fields except full_name and email are nullable
*/

-- Create the leads table
CREATE TABLE leads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  full_name text NOT NULL,
  company_name text,
  email text NOT NULL,
  service text,
  budget integer,
  message text
);

-- Create unique index on email to prevent duplicates
CREATE UNIQUE INDEX leads_email_unique_idx ON leads(email);

-- Create index on created_at for efficient sorting
CREATE INDEX leads_created_at_idx ON leads(created_at DESC);

-- Enable Row Level Security
ALTER TABLE leads ENABLE ROW LEVEL SECURITY;

-- Policy: Allow anonymous users to insert leads (for public chatbot form)
CREATE POLICY "Allow anonymous lead submissions"
  ON leads
  FOR INSERT
  TO anon
  WITH CHECK (true);

-- Policy: Allow authenticated users to read all leads (for admin purposes)
CREATE POLICY "Authenticated users can read all leads"
  ON leads
  FOR SELECT
  TO authenticated
  USING (true);